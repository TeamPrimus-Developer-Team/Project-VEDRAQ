    assert data["address"] == payload["address"]
    assert data["reporter_id"] == "RESP-001"
    assert data["people_affected_estimate"] == 450
    assert data["client_incident_id"] == "client-uuid-12345"

    # Initial history entry
    assert len(data["history"]) == 1
    assert data["history"][0]["status"] == "REPORTED"


