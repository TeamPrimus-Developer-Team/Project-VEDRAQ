def test_patch_incident_status_valid():
    """4. PATCH /api/incidents/{id} controlled lifecycle transitions."""
    create_resp = client.post(
        "/api/incidents",
        json={
            "title": "Landslide on Mountain Pass",
            "description": "Debris blocking both lanes",
            "disaster_type": "LANDSLIDE",
            "severity": "HIGH",
            "latitude": 27.750,
            "longitude": 85.550,
        },
    )
    inc_id = create_resp.json()["id"]

    # Transition 1: ACKNOWLEDGED
    r1 = client.patch(
        f"/api/incidents/{inc_id}",
        json={"status": "ACKNOWLEDGED", "note": "Dispatch coordinator assigned"},
    )
    assert r1.status_code == 200
    assert r1.json()["status"] == "ACKNOWLEDGED"
    assert len(r1.json()["history"]) == 2

    # Transition 2: IN_PROGRESS
    r2 = client.patch(
        f"/api/incidents/{inc_id}",
        json={"status": "IN_PROGRESS", "note": "Bulldozer and rescue team en route"},
    )
    assert r2.status_code == 200
    assert r2.json()["status"] == "IN_PROGRESS"
    assert len(r2.json()["history"]) == 3

    # Transition 3: RESOLVED
    r3 = client.patch(
        f"/api/incidents/{inc_id}",
        json={"status": "RESOLVED", "note": "Road cleared and verified safe"},
    )
    assert r3.status_code == 200
    assert r3.json()["status"] == "RESOLVED"
    assert len(r3.json()["history"]) == 4


