def test_multiple_incidents_unique_ids():
    """7 & 8. Multiple incidents generate guaranteed unique IDs."""
    ids = set()
    for i in range(10):
        resp = client.post(
            "/api/incidents",
            json={
                "title": f"Incident {i}",
                "description": f"Description for incident {i}",
                "disaster_type": "FLOOD",
                "severity": "MODERATE",
                "latitude": 25.310 + (i * 0.001),
                "longitude": 83.010 + (i * 0.001),
            },
        )
        assert resp.status_code == 201
        inc_id = resp.json()["id"]
        assert inc_id not in ids
        ids.add(inc_id)

    assert len(ids) == 10

    # Verify all 10 are retrieved
    list_resp = client.get("/api/incidents")
    assert list_resp.status_code == 200
    assert list_resp.json()["total"] == 10


