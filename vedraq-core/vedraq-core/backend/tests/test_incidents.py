def test_incident_persistence_during_process_lifetime():
    """11. Incident persistence across sequential calls."""
    # Create incident
    resp = client.post(
        "/api/incidents",
        json={
            "title": "Persistent Incident",
            "description": "Must persist across sequential requests",
            "disaster_type": "CYCLONE",
            "severity": "CRITICAL",
            "latitude": 25.315,
            "longitude": 83.065,
        },
    )
    inc_id = resp.json()["id"]

    # Multiple reads
    for _ in range(3):
        r = client.get(f"/api/incidents/{inc_id}")
        assert r.status_code == 200
        assert r.json()["id"] == inc_id

    # Update status
    client.patch(f"/api/incidents/{inc_id}", json={"status": "ACKNOWLEDGED"})

    # Verify update persisted
    r_after = client.get(f"/api/incidents/{inc_id}")
    assert r_after.status_code == 200
    assert r_after.json()["status"] == "ACKNOWLEDGED"


