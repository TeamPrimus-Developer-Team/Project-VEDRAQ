def test_location_consistency_varanasi_selected_city_not_equal_nearest_zone():
    """
    Selected city != nearest tactical zone case:
    Operator reports incident from Varanasi Center (25.3150, 83.0650).
    Address is preserved as 'Varanasi Center', and Core assigns nearest tactical zone 'Z14 Chaukaghat' (0.87 km).
    """
    payload = {
        "title": "Central Command Perimeter Flood",
        "description": "Rising floodwaters at central Varanasi sector",
        "disaster_type": "FLOOD",
        "severity": "HIGH",
        "latitude": 25.3150,
        "longitude": 83.0650,
        "address": "Varanasi Center",
    }
    resp = client.post("/api/incidents", json=payload)
    assert resp.status_code == 201
    data = resp.json()

    # Original coordinates and address are strictly preserved
    assert data["latitude"] == 25.3150
    assert data["longitude"] == 83.0650
    assert data["address"] == "Varanasi Center"

    # Nearest tactical zone is Chaukaghat (Z14)
    assert data["nearest_zone_id"] == "Z14"
    assert data["nearest_zone_name"] == "Chaukaghat"
    assert data["nearest_zone_distance_km"] < 1.5

    # Verification: selected city/address != nearest tactical zone name
    assert data["address"] != data["nearest_zone_name"]


